#!/bin/bash
# CI build script: CI variant of build_install.sh.
#
# Builds the packages listed in $PKGS (one directory name per line, or "all"),
# following the order from the 'build-order' file. Built packages are installed
# into the build environment (pacman -U) so later packages link against them,
# and every artifact (*.pkg.tar.zst) is copied into dist/.
#
# Unlike build_install.sh it:
#   - does not run repo_update / pacman -Syu (that is local-machine work)
#   - records the upstream ref in .upstream/<pkg> after a SUCCESSFUL build only,
#     so failed packages are retried on the next scheduled run
#   - fails the whole run at the end if any package failed
#   - publishes each package immediately after successful build + install,
#     so the [prince] repo is updated incrementally and next run can install it
#
# Intended to run as a non-root user (makepkg refuses root); pacman -U is done
# via passwordless sudo (configured by the CI workflow).

set -e -u -o pipefail
source "$(dirname "$(readlink -f "$0")")/common.sh"

DIST_DIR="$PWD/dist"
mkdir -p "$DIST_DIR"
failures=()
built_pkgs=()

# Track packages that were successfully published (so we only record refs for those)
published_pkgs=()

# Custom makepkg config: debug packages are built on demand only.
custom_makepkg_conf="$(mktemp)"
trap 'rm -f "$custom_makepkg_conf"' EXIT
{
    echo "# Generated by CI build script"
    echo "[[ -r /etc/makepkg.conf ]] && source /etc/makepkg.conf"
    echo "OPTIONS+=(!debug)"
} > "$custom_makepkg_conf"

# ---- Requested packages ----
mapfile -t requested < <(printf '%s\n' "${PKGS:-}" | sed '/^[[:space:]]*$/d')
build_all=false
mapfile -t all_pkgs < <(read_build_order)
if [[ ${#requested[@]} -eq 1 && "${requested[0]}" == "all" ]]; then
    build_all=true
fi

if [[ "$build_all" == false && ${#requested[@]} -eq 0 ]]; then
    echo "ERROR: PKGS is empty and build_all is false - nothing requested (CI env misconfigured)" >&2
    exit 1
fi

# ---- Publish a single package immediately ----
publish_package() {
    local pkg_file="$1"
    local dir="$2"

    echo "Publishing package (no push): $(basename "$pkg_file")"

    # Create a single-package staging directory
    local stage_dir
    stage_dir="$(mktemp -d)"
    cp -p "$pkg_file" "$stage_dir/"

    # Call publish_repo.sh on the staging directory (packages-staging branch)
    # It will clone the packages branch, replace superseded versions, rebuild db, push
    if ! DIST_DIR="$stage_dir" \
         GH_TOKEN="${GH_TOKEN:-}" \
         GH_REPO="${GH_REPO:-}" \
         PACKAGES_BRANCH=packages-staging bash github-ci/scripts/publish_repo.sh --no-push; then
        echo "ERROR: publish_repo.sh failed for $(basename "$pkg_file")" >&2
        rm -rf "$stage_dir"
        return 1
    fi

    rm -rf "$stage_dir"
    echo "Published locally: $(basename "$pkg_file")"
    return 0
}

# ---- Build one directory ----
process_directory() {
    local dir="$1"
    if [[ ! -d "$dir" ]]; then
        echo "Directory $dir does not exist. Skipping..." >&2
        return
    fi

    echo "============================================================"
    echo "Building in directory $dir"
    echo "============================================================"

    local makepkg_opts=(--syncdeps --noconfirm --config "$custom_makepkg_conf" --force)

    set +e
    (cd "$dir" && makepkg "${makepkg_opts[@]}")
    local makepkg_status=$?
    set -e

    if [[ $makepkg_status -ne 0 && $makepkg_status -ne 14 ]]; then
        echo "makepkg failed for $dir with status $makepkg_status." >&2
        failures+=("$dir")
        return
    fi

    [[ $makepkg_status -eq 14 ]] && echo "$dir: already built for current version."

    # Collect built package files
    local pkg_path
    local built=()
    while IFS= read -r pkg_path; do
        if [[ -f "$pkg_path" ]]; then
            built+=("$pkg_path")
        fi
    done < <(cd "$dir" && makepkg "${makepkg_opts[@]}" --packagelist 2>/dev/null)

    if [[ ${#built[@]} -eq 0 ]]; then
        echo "No package files produced for $dir." >&2
        failures+=("$dir")
        return
    fi

    # Install so later packages in build-order build against them
    sudo pacman -U --noconfirm --ask 4 --overwrite '*' "${built[@]}" || { failures+=("$dir"); return; }

    # Publish each package immediately after install
    local pkg
    for pkg in "${built[@]}"; do
        if ! publish_package "$pkg" "$dir"; then
            failures+=("$dir")
            return
        fi
        # Only record as published if publish succeeded
        published_pkgs+=("$dir")
    done

    # Collect artifacts for final release upload
    for pkg in "${built[@]}"; do
        cp -p "$pkg" "$DIST_DIR/"
        built_pkgs+=("$(basename "$pkg")")
    done

    # Record upstream ref only after successful build AND publish
    local url ref
    url="$(get_pkg_url "$dir")"
    # Use same ref detection as check_upstream.sh
    if is_tag_based "$dir"; then
        ref="$(get_latest_tag_ref "$url")"
    else
        ref="$(get_head_ref "$url")"
    fi
    if [[ -n "$ref" ]]; then
        store_ref "$dir" "$ref"
    fi

    echo "Build successful for $dir."
}

# ---- Main loop over build-order ----
for dir in "${all_pkgs[@]}"; do
    if [[ "$build_all" == true ]]; then
        process_directory "$dir"
        continue
    fi
    if [[ ${#requested[@]} -gt 0 ]] && printf '%s\n' "${requested[@]}" | grep -qx "$dir"; then
        process_directory "$dir"
    fi
done

# ---- Summary ----
if [[ -n "${GITHUB_STEP_SUMMARY:-}" ]]; then
    {
        echo "## Build result"
        echo ""
        if [[ ${#built_pkgs[@]} -gt 0 ]]; then
            echo "Built packages (${#built_pkgs[@]}):"
            for p in "${built_pkgs[@]}"; do echo "- \`$p\`"; done
        fi
        if [[ ${#failures[@]} -gt 0 ]]; then
            echo ""
            echo "**Failed (${#failures[@]}):**"
            for f in "${failures[@]}"; do echo "- \`$f\`"; done
        fi
    } >> "$GITHUB_STEP_SUMMARY"
fi

if [[ ${#failures[@]} -gt 0 ]]; then
    echo "The following packages failed: ${failures[*]}" >&2
    exit 1
fi

if [[ ${#built_pkgs[@]} -eq 0 ]]; then
    echo "ERROR: build completed with zero packages (empty PKGS match or missing artifacts)" >&2
    exit 1
fi

if [[ ${#built_pkgs[@]} -eq 0 ]]; then
    echo "Nothing was built."
fi

echo "CI build script finished. Artifacts in $DIST_DIR"